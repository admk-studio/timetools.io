// Command tznames indexes every zone and link in Go's embedded timezone database.
package main

import (
	"archive/zip"
	"flag"
	"fmt"
	"log"
	"path/filepath"
	"runtime"
	"sort"
)

func main() {
	path := flag.String("zip", filepath.Join(runtime.GOROOT(), "lib", "time", "zoneinfo.zip"), "Go timezone archive")
	flag.Parse()
	z, err := zip.OpenReader(*path)
	if err != nil {
		log.Fatal(err)
	}
	defer z.Close()
	var names []string
	for _, f := range z.File {
		if !f.FileInfo().IsDir() {
			names = append(names, f.Name)
		}
	}
	sort.Strings(names)
	fmt.Println("// Code generated by gen/tznames from Go's zoneinfo.zip; DO NOT EDIT.")
	fmt.Println("package tz\n\nvar ianaNames = []string{")
	for _, name := range names {
		fmt.Printf("\t%q,\n", name)
	}
	fmt.Println("}")
}
