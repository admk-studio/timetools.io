// Command zones regenerates internal/tz/zones_gen.go from the IANA
// zone1970.tab file. The generated table is committed so that builds
// never depend on the host having tzdata installed.
//
// Usage:
//
//	go run ./gen/zones -tab /usr/share/zoneinfo/zone1970.tab > internal/tz/zones_gen.go
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	tab := flag.String("tab", "/usr/share/zoneinfo/zone1970.tab", "path to zone1970.tab")
	flag.Parse()

	f, err := os.Open(*tab)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	type zone struct {
		name      string
		countries string
		lat, lon  float64
	}
	var zones []zone

	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) < 3 {
			log.Fatalf("malformed line: %q", line)
		}
		lat, lon, err := parseISO6709(fields[1])
		if err != nil {
			log.Fatalf("bad coordinates %q for %s: %v", fields[1], fields[2], err)
		}
		zones = append(zones, zone{
			name:      fields[2],
			countries: fields[0],
			lat:       lat,
			lon:       lon,
		})
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	sort.Slice(zones, func(i, j int) bool { return zones[i].name < zones[j].name })

	// Flag city-name collisions so the resolver's override table can be
	// kept honest. These go to stderr; the generated file goes to stdout.
	byCity := map[string][]string{}
	for _, z := range zones {
		city := z.name[strings.LastIndexByte(z.name, '/')+1:]
		key := strings.ToLower(strings.NewReplacer("_", "", "-", "").Replace(city))
		byCity[key] = append(byCity[key], z.name)
	}
	for key, names := range byCity {
		if len(names) > 1 {
			fmt.Fprintf(os.Stderr, "collision %q: %s\n", key, strings.Join(names, ", "))
		}
	}

	fmt.Println("// Code generated by gen/zones; DO NOT EDIT.")
	fmt.Println("//")
	fmt.Printf("// Source: zone1970.tab (%d canonical zones).\n", len(zones))
	fmt.Println()
	fmt.Println("package tz")
	fmt.Println()
	fmt.Println("var zones = []Zone{")
	for _, z := range zones {
		fmt.Printf("\t{Name: %q, Countries: %q, Lat: %s, Lon: %s, HasCoords: true},\n",
			z.name, z.countries, trimFloat(z.lat), trimFloat(z.lon))
	}
	fmt.Println("}")
}

// parseISO6709 handles the two coordinate forms used by zone1970.tab:
// ±DDMM±DDDMM and ±DDMMSS±DDDMMSS.
func parseISO6709(s string) (lat, lon float64, err error) {
	split := strings.LastIndexAny(s[1:], "+-") + 1
	if split == 0 {
		return 0, 0, fmt.Errorf("no longitude sign")
	}
	lat, err = parseAngle(s[:split], 2)
	if err != nil {
		return 0, 0, err
	}
	lon, err = parseAngle(s[split:], 3)
	return lat, lon, err
}

func parseAngle(s string, degDigits int) (float64, error) {
	if len(s) < 1+degDigits+2 {
		return 0, fmt.Errorf("angle %q too short", s)
	}
	sign := 1.0
	if s[0] == '-' {
		sign = -1
	}
	deg, err := strconv.Atoi(s[1 : 1+degDigits])
	if err != nil {
		return 0, err
	}
	min, err := strconv.Atoi(s[1+degDigits : 1+degDigits+2])
	if err != nil {
		return 0, err
	}
	sec := 0
	if rest := s[1+degDigits+2:]; rest != "" {
		if sec, err = strconv.Atoi(rest); err != nil {
			return 0, err
		}
	}
	return sign * (float64(deg) + float64(min)/60 + float64(sec)/3600), nil
}

func trimFloat(f float64) string {
	return strconv.FormatFloat(f, 'f', 4, 64)
}
